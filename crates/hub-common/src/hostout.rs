//! ホストへ出す行を必ず**行頭から**始めるための出口 (Refs ippoan/alc-app-s3#268)。
//!
//! `docs/console-protocol.md` は「1 行 1 メッセージ」を定めているが、起動直後は
//! ログ行が途中でバイトを落とすことがあり (USB Serial/JTAG の TX バッファが
//! 溢れる・リセット直後のストリームが途中から始まる)、そこへ応答や `EVT ` 行が
//! **連結して**しまう。実測:
//!
//! ```text
//! …nfc: 待受開始 port=0     ← ` sda=2 scl=1\n` を落とした行
//! EVT NFC_READY port=0      ← その尻に連結し、ホストの行頭一致から外れる
//! ```
//!
//! ホスト側は 3 本 (`useSerialArbiter` / `docs/index.html` / `docs/atoms3-nfc.html`)
//! あり、行中検索で拾い直しているのは 1 本だけ。**出す側が必ず改行から始めれば**
//! ホストの行分割がそこで切ってくれるので、3 本とも直る。
//!
//! 空行はホスト 3 本ともすでに捨てている (`if (line)` / `if (row.trim())`) ため、
//! 先頭に改行が 1 つ増えても互換性は壊れない。
//!
//! 呼ぶのは**出口の 3 か所だけ**で、個々の `println!` は書き換えない:
//!
//! | 呼ぶ場所 | 何の直前か |
//! |---|---|
//! | `hub-drivers::console::spawn_reader` | コマンドを捌く直前 (AtomS3 系 4 機種) |
//! | `hub-drivers::host_link::drain_buffer` | 同上 (CoreS3 系) |
//! | [`crate::evtlog::emit`] | `EVT ` 行 — **コマンドと無関係に非同期で出る**ので、上 2 つでは覆えない |

/// 直後の出力が確実に行頭から始まるようにする (改行を 1 つ出すだけ)。
///
/// 途中で終わっている行があればここで閉じ、無ければ空行が 1 つ増えるだけ。
pub fn begin_line() {
    print!("\n");
}

/// 1 行を行頭から出す (改行 + 本文 + 改行)。
///
/// [`begin_line`] + `println!` と同じだが、**1 回の write で出す**ので、
/// 他のタスクの出力が改行と本文のあいだに割り込めない。`EVT ` 行のように
/// 非同期に出るものはこちらを使う。
pub fn line(text: &str) {
    println!("\n{text}");
}
